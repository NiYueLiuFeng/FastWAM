def add_generate_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--dataset", action="append", required=True, metavar="PATH",
                        help="LeRobot dataset root (repeatable; must share fps/cameras/dims)")
    parser.add_argument("--name", default=None, help="config name; defaults to the dataset directory name")
    parser.add_argument("--camera", action="append", default=[], metavar="KEY",
                        help="camera key (without observation.images.) to include, repeatable/ordered")
    parser.add_argument("--exclude-camera", action="append", default=[], metavar="KEY")
    parser.add_argument("--intersect-cameras", action="store_true",
                        help="keep only cameras present in every dataset")
    parser.add_argument("--resize", nargs=2, type=int, default=[224, 224], metavar=("H", "W"),
                        help="per-camera resize target (default: 224 224)")
    parser.add_argument("--concat", choices=["auto", "horizontal", "vertical", "robotwin", "null"],
                        default="auto", help="multi-camera concat layout (default: auto)")
    parser.add_argument("--video-size", nargs=2, type=int, default=None, metavar=("H", "W"),
                        help="final concatenated size; H/W must be multiples of 16")
    parser.add_argument("--num-frames", type=int, default=DEFAULT_NUM_FRAMES)
    parser.add_argument("--action-video-freq-ratio", type=int, default=DEFAULT_FREQ_RATIO)
    parser.add_argument("--global-sample-stride", type=int, default=1)
    parser.add_argument("--action-feature", default="action", metavar="NAME",
                        help="LeRobot action feature/column name (default: action; "
                             "e.g. `actions` for datasets that do not follow the convention)")
    parser.add_argument("--state-feature", default="observation.state", metavar="NAME",
                        help="LeRobot state feature/column name (default: observation.state)")
    parser.add_argument("--action-key", action="append", default=[],
                        help="select <action-feature>.<key> sub-features (repeatable)")
    parser.add_argument("--state-key", action="append", default=[],
                        help="select <state-feature>.<key> sub-features (repeatable)")
    parser.add_argument("--delta-mask", default=None,
                        help="comma-separated true/false per action dim, or all-false/all-true")
    parser.add_argument("--norm-mode", choices=["min/max", "z-score"], default="min/max")
    parser.add_argument("--val-proportion", type=float, default=0.0)
    parser.add_argument("--context-len", type=int, default=DEFAULT_CONTEXT_LEN)
    parser.add_argument("--cache-dir", default=None, help="text embedding cache dir")
    parser.add_argument("--model", choices=MODEL_CHOICES, default=DEFAULT_MODEL)
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    parser.add_argument("--num-workers", type=int, default=DEFAULT_NUM_WORKERS)
    parser.add_argument("--epochs", type=int, default=DEFAULT_EPOCHS)
    parser.add_argument("--gradient-accumulation-steps", "--grad-accum", dest="grad_accum",
                        type=int, default=DEFAULT_GRAD_ACCUM,
                        help="gradient accumulation steps (effective batch = batch-size x GPUs x N)")
    parser.add_argument("--max-steps", type=int, default=DEFAULT_MAX_STEPS,
                        help="fixed optimizer steps (0/unset = derive from --epochs and dataset size)")
    parser.add_argument("--lr", type=float, default=DEFAULT_LR)
    parser.add_argument("--save-every", type=int, default=DEFAULT_SAVE_EVERY)
    parser.add_argument("--keep-last", type=int, default=DEFAULT_KEEP_LAST_N,
                        help="keep only the newest N checkpoints (0 = keep all)")
    parser.add_argument("--force", action="store_true", help="overwrite hand-written target configs")
    parser.add_argument("--print-name", action="store_true", help="print only the generated task name")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Prepare FastWAM configs for a custom LeRobot dataset and verify training prerequisites.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate = subparsers.add_parser("generate", help="probe a dataset and write data/task configs")
    add_generate_arguments(generate)
    generate.set_defaults(func=cmd_generate)

    importer = subparsers.add_parser("import-config", help="import an existing task/data config")
    importer.add_argument("--task", default=None, help="task config name or .yaml path")
    importer.add_argument("--task-file", default=None, help="task config .yaml path (alias of --task)")
    importer.add_argument("--data-config", default=None, help="data config name or .yaml path")
    importer.add_argument("--model", choices=MODEL_CHOICES, default=DEFAULT_MODEL)
    importer.add_argument("--force", action="store_true")
    importer.add_argument("--print-name", action="store_true")
    importer.set_defaults(func=cmd_import_config)

    override = subparsers.add_parser("override-form", help="emit key=value or +key=value overrides")
    override.add_argument("--task", required=True)
    override.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    override.set_defaults(func=cmd_override_form)

    verify = subparsers.add_parser("verify", help="check a composed config and training prerequisites")
    verify.add_argument("--task", required=True)
    verify.add_argument("--override", action="append", default=[], metavar="KEY=VALUE")
    verify.add_argument("--gpus", type=int, default=1)
    verify.add_argument("--online-text-encode", action="store_true")
    verify.add_argument("--random-backbone-init", action="store_true")
    verify.add_argument("--skip-prereq-check", action="store_true")
    verify.set_defaults(func=cmd_verify)

    return parser


def main(argv: Sequence[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    known_commands = {"generate", "import-config", "override-form", "verify"}
    if argv and argv[0] in {"-h", "--help"}:
        build_parser().print_help()
        return 0
    if argv and not argv[0].startswith("-") and argv[0] not in known_commands:
        die(f"未知子命令: {argv[0]}")
    if argv and argv[0].startswith("-"):
        # Convenience: `prepare_custom_training.py --dataset ...` means generate.
        argv = ["generate", *argv]

    parser = build_parser()
    args = parser.parse_args(argv)

    if args.command == "generate" and args.dataset is None:
        die("--dataset is required")
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
