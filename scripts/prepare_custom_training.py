@dataclass
class VectorSpec:
    key: str  # shape_meta key: "default" or the `base.suffix` part
    dim: int
    lerobot_key: str  # actual LeRobot feature/column name


@dataclass
class Probe:
    path: Path
    version: str
    reader: str
    video_backend: str | None
    fps: int
    cameras: "dict[str, tuple[int, int, int]]"  # key -> raw CHW
    action: list[VectorSpec]
    state: list[VectorSpec]
    max_episode_length: int | None


def classify_version(info: dict[str, Any], path: Path) -> tuple[str, str, str | None]:
    raw = str(info.get("codebase_version", "")).strip()
    if not raw:
        die(f"{path}/meta/info.json 缺少 codebase_version")
    cleaned = raw[1:] if raw.lower().startswith("v") else raw
    match = re.match(r"^(\d+)\.(\d+)", cleaned)
    if not match:
        die(f"无法识别的 codebase_version: {raw!r} ({path})")
    major, minor = int(match.group(1)), int(match.group(2))
    if (major, minor) in {(2, 0), (2, 1)}:
        return f"{major}.{minor}", READER_V2, None
    if (major, minor) == (3, 0):
        return "3.0", READER_V3, "pyav"
    die(
        f"不支持的 LeRobot codebase_version {raw!r} ({path})；"
        "仅支持 2.0 / 2.1 / 3.0"
    )
    raise AssertionError("unreachable")


def parse_camera_shape(feature: dict[str, Any], key: str) -> tuple[int, int, int]:
    """Return raw shape as CHW regardless of the metadata's HWC/CHW convention."""
    shape = feature.get("shape")
    names = feature.get("names")
    if shape is None:
        info = feature.get("info") or {}
        height = info.get("video.height")
        width = info.get("video.width")
        channels = info.get("video.channels", 3)
        if height is None or width is None:
            die(f"相机特征 {key!r} 缺少 shape 信息")
        shape = [height, width, channels]
        names = ["height", "width", "channels"]

    shape = [int(v) for v in shape]
    if len(shape) != 3:
        die(f"相机特征 {key!r} 的 shape 必须是 3 维 (HWC 或 CHW)，实际为 {shape}")

    if names:
        lowered = [str(n).lower() for n in names]
        channel_name = "channels" if "channels" in lowered else ("channel" if "channel" in lowered else None)
        if "height" in lowered and "width" in lowered and channel_name is not None:
            return (
                shape[lowered.index(channel_name)],
                shape[lowered.index("height")],
                shape[lowered.index("width")],
            )

    if shape[-1] in (1, 3, 4) and shape[0] not in (1, 3, 4):
        height, width, channels = shape
    elif shape[0] in (1, 3, 4):
        channels, height, width = shape
    else:
        die(
            f"无法判断相机特征 {key!r} 的布局: shape={shape}, names={names}。"
            "请使用 HWC 或 CHW 布局，或提供 names。"
        )
    return channels, height, width


def _vector_feature_names(features: dict[str, Any]) -> list[str]:
    """Feature names whose shape is 1-D, i.e. usable as action/state vectors."""
    names = []
    for key, feature in features.items():
        shape = feature.get("shape")
        if shape is not None and len(shape) == 1:
            names.append(key)
    return sorted(names)


def parse_vector_specs(
    features: dict[str, Any],
    base_key: str,
    label: str,
    flag: str,
) -> list[VectorSpec]:
    """Find `base_key` or its `base_key.suffix` variants.

    `base_key` is the LeRobot feature name; it defaults to the standard
    `action` / `observation.state` but can be any column (e.g. `actions`) when
    the dataset does not follow the LeRobot convention.
    """
    if base_key in features:
        feature = features[base_key]
        return [VectorSpec("default", _vector_dim(feature, base_key), base_key)]

    prefix = base_key + "."
    specs: list[VectorSpec] = []
    for key, feature in features.items():
        if key.startswith(prefix):
            specs.append(VectorSpec(key[len(prefix):], _vector_dim(feature, key), key))
    if not specs:
        candidates = _vector_feature_names(features)
        die(
            f"数据集中找不到 {label} 特征 {base_key!r}。"
            f"若数据集没有采用标准命名，请用 {flag} 指定列名；"
            f"当前 1 维特征: {candidates}"
        )
    return specs


def _vector_dim(feature: dict[str, Any], key: str) -> int:
    shape = feature.get("shape")
    if shape is None:
        return 1
    shape = [int(v) for v in shape]
    if len(shape) == 0:
        return 1
    if len(shape) > 1:
        die(f"特征 {key!r} 必须是 1 维向量，实际 shape={shape}")
    return shape[0]


def read_episode_lengths(path: Path, version: str) -> list[int]:
    try:
        if version.startswith("2"):
            episodes_path = path / "meta" / "episodes.jsonl"
            if not episodes_path.exists():
                return []
            lengths: list[int] = []
            with episodes_path.open("r", encoding="utf-8") as handle:
                for line in handle:
                    line = line.strip()
                    if not line:
                        continue
                    record = json.loads(line)
                    if "length" in record:
                        lengths.append(int(record["length"]))
            return lengths

        episodes_dir = path / "meta" / "episodes"
        if not episodes_dir.exists():
            return []
        import pyarrow.parquet as pq  # local import: only needed for v3 probes

        lengths = []
        for parquet_path in sorted(episodes_dir.rglob("*.parquet")):
            table = pq.read_table(parquet_path, columns=["length"])
            lengths.extend(int(v) for v in table.column("length").to_pylist())
        return lengths
    except Exception as exc:  # best-effort only
        log(f"warning: 无法读取 episode 长度 ({path}): {exc}")
        return []


def check_parquet_columns(path: Path, features: dict[str, Any]) -> None:
    """info.json 声明的列必须真的存在于 data parquet 里。

    训练时的 v3 读取器直接用 `columns=list(features)` 选列，列名对不上就会在
    `Dataset.from_parquet` 里抛 `ArrowInvalid: No match for FieldRef.Name(...)`，
    而且是在模型加载完之后才炸，排查成本很高。这里提前拦住。
    """
    try:
        import pyarrow.parquet as pq
    except ModuleNotFoundError:
        return  # 没有 pyarrow 时保持原来的行为

    files = sorted((path / "data").glob("*/*.parquet"))
    if not files:
        files = sorted((path / "data").rglob("*.parquet"))
    if not files:
        return

    try:
        columns = set(pq.ParquetFile(files[0]).schema_arrow.names)
    except Exception as exc:  # 损坏的 parquet 交给训练阶段报错
        log(f"warning: 读取 {files[0]} 的列名失败: {exc}")
        return

    declared = {key for key, feature in features.items() if str(feature.get("dtype")) != "video"}
    missing = sorted(declared - columns)
    if not missing:
        return

    hint = ""
    if "frame_index" in missing and "frame_idx" in columns:
        hint = (
            "\n  疑似列名不一致：meta 里是 `frame_index`，parquet 里是 `frame_idx`。"
            f"\n  修复：python scripts/fix_dataset_columns.py --dataset {path} --write"
        )
    die(
        f"{path}/meta/info.json 声明的列在 data parquet 中不存在: {missing}"
        f"\n  parquet 现有列: {sorted(columns)}{hint}"
    )


def read_task_texts(path: Path) -> list[str]:
    """Read unique-free task strings from meta/tasks.jsonl or meta/tasks.parquet."""
    jsonl_path = path / "meta" / "tasks.jsonl"
    parquet_path = path / "meta" / "tasks.parquet"
    if jsonl_path.exists():
        texts: list[str] = []
        with jsonl_path.open("r", encoding="utf-8") as handle:
            for line_idx, line in enumerate(handle, start=1):
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                if "task" not in record:
                    die(f"{jsonl_path}:{line_idx} 缺少 `task` 字段")
                texts.append(str(record["task"]))
        return texts

    if parquet_path.exists():
        import pandas as pd  # local import: keeps generation stdlib-only

        frame = pd.read_parquet(parquet_path)
        if "task" in frame.columns:
            return [str(v) for v in frame["task"].tolist()]
        # lerobot 3.0 stores the task text in the index (tasks.iloc[idx].name).
        return [str(v) for v in frame.index.tolist()]

    die(f"{path} 缺少 meta/tasks.jsonl 与 meta/tasks.parquet")
    raise AssertionError("unreachable")


def probe_dataset(
    path: Path,
    action_feature: str = "action",
    state_feature: str = "observation.state",
) -> Probe:
    info_path = path / "meta" / "info.json"
    if not info_path.exists():
        die(f"不是 LeRobot 数据集（缺少 {info_path}）")
    info = _read_json(info_path)
    version, reader, video_backend = classify_version(info, path)
    features = info.get("features") or {}

    cameras: dict[str, tuple[int, int, int]] = {}
    for key, feature in features.items():
        dtype = str(feature.get("dtype", ""))
        if dtype not in {"image", "video"}:
            continue
        if not key.startswith("observation.images."):
            log(f"warning: 跳过非 observation.images.* 相机特征 {key!r}")
            continue
        short_key = key[len("observation.images."):]
        raw_shape = parse_camera_shape(feature, key)
        if raw_shape[0] != 3:
            log(f"warning: 跳过非 RGB 相机特征 {key!r}（channels={raw_shape[0]}）")
            continue
        cameras[short_key] = raw_shape

    if not cameras:
        die(f"{path} 中没有任何 RGB 相机（observation.images.*）")

    action = parse_vector_specs(features, action_feature, "action", "--action-feature")
    state = parse_vector_specs(features, state_feature, "state", "--state-feature")
    check_parquet_columns(path, features)
    lengths = read_episode_lengths(path, version)

    return Probe(
        path=path,
        version=version,
        reader=reader,
        video_backend=video_backend,
        fps=int(info.get("fps", 0) or 0),
        cameras=cameras,
        action=action,
        state=state,
        max_episode_length=max(lengths) if lengths else None,
    )


