@dataclass
class Policy:
    name: str | None = None
    camera_keys: list[str] = field(default_factory=list)
    exclude_cameras: list[str] = field(default_factory=list)
    intersect_cameras: bool = False
    resize: tuple[int, int] = (224, 224)
    concat: str = "auto"
    video_size: tuple[int, int] | None = None
    num_frames: int = DEFAULT_NUM_FRAMES
    action_video_freq_ratio: int = DEFAULT_FREQ_RATIO
    global_sample_stride: int = 1
    action_feature: str = "action"
    state_feature: str = "observation.state"
    action_keys: list[str] = field(default_factory=list)
    state_keys: list[str] = field(default_factory=list)
    delta_mask: str | None = None
    norm_mode: str = "min/max"
    val_proportion: float = 0.0
    context_len: int = DEFAULT_CONTEXT_LEN
    cache_dir: str | None = None
    use_text_cache: bool = True
    model: str = DEFAULT_MODEL
    batch_size: int = DEFAULT_BATCH_SIZE
    num_workers: int = DEFAULT_NUM_WORKERS
    num_epochs: int = DEFAULT_EPOCHS
    gradient_accumulation_steps: int = DEFAULT_GRAD_ACCUM
    learning_rate: float = DEFAULT_LR
    save_every: int = DEFAULT_SAVE_EVERY
    keep_last_n: int = DEFAULT_KEEP_LAST_N
    max_steps: int | None = DEFAULT_MAX_STEPS


@dataclass
class Plan:
    datasets: list[Path]
    version: str
    reader: str
    video_backend: str | None
    cameras: list[tuple[str, tuple[int, int, int]]]
    action: list[VectorSpec]
    state: list[VectorSpec]
    video_size: tuple[int, int]
    concat: str | None
    delta_masks: list[bool]
    policy: Policy
    max_episode_length: int | None


def _select_vector_specs(specs: list[VectorSpec], selected: list[str], label: str) -> list[VectorSpec]:
    if not selected:
        if len(specs) > 1:
            names = ", ".join(spec.key for spec in specs)
            die(f"数据集有多个 {label} 特征（{names}），请用 --{label}-key 指定（可重复）")
        return specs
    by_key = {spec.key: spec for spec in specs}
    missing = [key for key in selected if key not in by_key]
    if missing:
        die(f"找不到 {label} key: {missing}；可选: {sorted(by_key)}")
    return [by_key[key] for key in selected]


def merge_probes(probes: Sequence[Probe], policy: Policy) -> Plan:
    first = probes[0]
    for probe in probes[1:]:
        if probe.version != first.version:
            die(f"数据集版本不一致: {first.path} v{first.version} vs {probe.path} v{probe.version}")
        if probe.fps != first.fps:
            die(f"数据集 fps 不一致: {first.path} {first.fps} vs {probe.path} {probe.fps}")
        if probe.action != first.action:
            die(f"action 维度/key 不一致: {first.path} {first.action} vs {probe.path} {probe.action}")
        if probe.state != first.state:
            die(f"state 维度/key 不一致: {first.path} {first.state} vs {probe.path} {probe.state}")

    all_camera_keys = list(first.cameras)
    if policy.intersect_cameras:
        selected = [
            key for key in all_camera_keys
            if all(key in probe.cameras for probe in probes) and key not in policy.exclude_cameras
        ]
        if not selected:
            die("--intersect-cameras 后没有公共相机")
    elif policy.camera_keys:
        selected = [key for key in policy.camera_keys if key not in policy.exclude_cameras]
        for key in selected:
            for probe in probes:
                if key not in probe.cameras:
                    die(f"数据集 {probe.path} 中找不到相机 {key!r}；可选: {list(probe.cameras)}")
    else:
        selected = [key for key in all_camera_keys if key not in policy.exclude_cameras]
        for probe in probes[1:]:
            if set(probe.cameras) != set(first.cameras):
                die(
                    f"数据集相机集合不一致: {first.path} {list(first.cameras)} vs "
                    f"{probe.path} {list(probe.cameras)}；可用 --intersect-cameras 或 --camera 指定"
                )

    if not selected:
        die("没有可用的相机")

    cameras: list[tuple[str, tuple[int, int, int]]] = []
    for key in selected:
        shapes = {probe.cameras[key] for probe in probes if key in probe.cameras}
        if len(shapes) > 1:
            log(f"warning: 相机 {key!r} 在各数据集中的分辨率不同: {sorted(shapes)}")
        cameras.append((key, first.cameras[key]))

    action = _select_vector_specs(first.action, policy.action_keys, "action")
    state = _select_vector_specs(first.state, policy.state_keys, "state")

    action_dim = sum(spec.dim for spec in action)
    delta_masks = parse_delta_mask(policy.delta_mask, action)

    resize_h, resize_w = policy.resize
    concat = policy.concat
    if concat == "auto":
        concat = None if len(cameras) == 1 else "horizontal"
    if concat == "null":
        concat = None

    if policy.video_size is not None:
        video_size = policy.video_size
    elif concat is None:
        if len(cameras) != 1:
            die("多相机且 --concat null 时，请显式提供 --video-size")
        video_size = (resize_h, resize_w)
    elif concat == "horizontal":
        video_size = (resize_h, resize_w * len(cameras))
    elif concat == "vertical":
        video_size = (resize_h * len(cameras), resize_w)
    elif concat == "robotwin":
        die("robotwin 拼接布局与相机顺序/尺寸强相关，请显式提供 --video-size")
    else:
        die(f"未知 concat 布局: {concat}")

    max_length = min(
        (probe.max_episode_length for probe in probes if probe.max_episode_length is not None),
        default=None,
    )

    validate_policy(policy, video_size, action_dim, len(cameras), max_length)

    if policy.cache_dir:
        cache_dir = policy.cache_dir
        if os.path.isabs(cache_dir):
            cache_dir = _dataset_yaml_path(Path(cache_dir))
    else:
        name = policy.name or first.path.name
        cache_dir = f"./data/text_embeds_cache/autogen_{_sanitize(name)}"

    policy.cache_dir = cache_dir

    return Plan(
        datasets=[probe.path for probe in probes],
        version=first.version,
        reader=first.reader,
        video_backend=first.video_backend,
        cameras=cameras,
        action=action,
        state=state,
        video_size=video_size,
        concat=concat,
        delta_masks=delta_masks,
        policy=policy,
        max_episode_length=max_length,
    )


def parse_delta_mask(raw: str | None, action: list[VectorSpec]) -> list[bool]:
    total = sum(spec.dim for spec in action)
    if raw is None:
        return [False] * total
    text = raw.strip().lower()
    if text in {"all-false", "false", "none"}:
        return [False] * total
    if text in {"all-true", "true"}:
        return [True] * total
    parts = [part.strip() for part in text.split(",") if part.strip()]
    values = []
    for part in parts:
        if part in {"1", "true", "yes", "y"}:
            values.append(True)
        elif part in {"0", "false", "no", "n"}:
            values.append(False)
        else:
            die(f"无法解析 --delta-mask 项: {part!r}")
    if len(values) != total:
        die(f"--delta-mask 长度 {len(values)} 与 action 维度 {total} 不一致")
    return values


def validate_policy(
    policy: Policy,
    video_size: tuple[int, int],
    action_dim: int,
    num_cameras: int,
    max_episode_length: int | None,
) -> None:
    resize_h, resize_w = policy.resize
    if resize_h <= 0 or resize_w <= 0:
        die(f"--resize 必须是正整数，实际为 {policy.resize}")
    height, width = video_size
    if height <= 0 or width <= 0 or height % 16 or width % 16:
        die(f"video_size 的 H/W 必须是 16 的正整数倍，实际为 {video_size}")
    if policy.num_frames < 2:
        die(f"--num-frames 必须 >= 2，实际为 {policy.num_frames}")
    if policy.action_video_freq_ratio <= 0:
        die(f"--action-video-freq-ratio 必须 > 0，实际为 {policy.action_video_freq_ratio}")
    if (policy.num_frames - 1) % policy.action_video_freq_ratio != 0:
        die(
            f"(num_frames - 1)={policy.num_frames - 1} 必须能被 "
            f"action_video_freq_ratio={policy.action_video_freq_ratio} 整除"
        )
    video_frames = (policy.num_frames - 1) // policy.action_video_freq_ratio
    if video_frames % 4 != 0:
        die(f"视频帧数 {video_frames} 必须是 4 的倍数（VAE tokenization 约束）")
    if policy.global_sample_stride <= 0:
        die(f"--global-sample-stride 必须 > 0，实际为 {policy.global_sample_stride}")
    if policy.context_len <= 0:
        die(f"--context-len 必须 > 0，实际为 {policy.context_len}")
    if not 0.0 <= policy.val_proportion < 1.0:
        die(f"--val-proportion 必须在 [0, 1) 内，实际为 {policy.val_proportion}")
    if policy.norm_mode not in {"min/max", "z-score"}:
        die(f"--norm-mode 只支持 min/max 或 z-score，实际为 {policy.norm_mode}")
    if action_dim <= 0:
        die("action 维度必须 > 0")
    if num_cameras <= 0:
        die("相机数量必须 > 0")

    window = (policy.num_frames - 1) * policy.global_sample_stride + 1
    if max_episode_length is not None:
        if max_episode_length < window:
            die(
                f"最长 episode 只有 {max_episode_length} 帧，小于采样窗口 {window} 帧。"
                f"请调小 --num-frames / --global-sample-stride，或使用更长的 episode。"
            )
        if max_episode_length == window:
            log(f"warning: episode 长度恰好等于采样窗口 {window} 帧，几乎没有余量")


