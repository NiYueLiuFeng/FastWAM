def _flavor(text: str) -> str | None:
    if "@package _global_" in text or re.search(r"^defaults:\s*$", text, re.MULTILINE):
        return "task"
    if re.search(r"^train:\s*$", text, re.MULTILINE):
        return "data"
    return None


def _copy_config(source: Path, flavor: str, force: bool) -> tuple[str, Path]:
    target_dir = CONFIGS / ("task" if flavor == "task" else "data")
    name = source.stem
    target = target_dir / f"{name}.yaml"
    if source.resolve() == target.resolve():
        return name, target

    text = source.read_text(encoding="utf-8")
    detected = _flavor(text)
    if detected != flavor:
        die(f"{source} 看起来是 {detected or '未知'} 配置，而不是 {flavor} 配置")

    if target.exists():
        existing = target.read_text(encoding="utf-8")
        if existing == text:
            return name, target
        if not force:
            die(f"目标配置已存在且内容不同: {target}（使用 --force 覆盖）")
    _atomic_write(target, text)
    return name, target


def _task_data_override(text: str) -> str | None:
    match = re.search(r"override\s+/data:\s*([A-Za-z0-9_\-/]+)", text)
    return match.group(1) if match else None


def _task_model_override(text: str) -> str:
    match = re.search(r"override\s+/model:\s*([A-Za-z0-9_\-/]+)", text)
    return match.group(1) if match else DEFAULT_MODEL


def _data_config_import(args: argparse.Namespace) -> str:
    value = args.data_config
    candidate = Path(value).expanduser()
    if candidate.exists():
        name, target = _copy_config(candidate.resolve(), "data", args.force)
        text = target.read_text(encoding="utf-8")
    else:
        name = value[:-5] if value.endswith(".yaml") else value
        target = CONFIGS / "data" / f"{name}.yaml"
        if not target.exists():
            die(f"找不到 data 配置: {value}（既不是文件，也不在 configs/data/ 下）")
        text = target.read_text(encoding="utf-8")

    if _flavor(text) != "data":
        die(f"{target} 不是合法的 data 配置（顶层需要 train: 节点）")

    task_name = f"autogen_{_sanitize(name)}"
    wrapper = (
        "# @package _global_\n"
        f"# {AUTOGEN_MARKER}\n"
        f"# data_config: {name}\n"
        "defaults:\n"
        f"  - override /data: {name}\n"
        f"  - override /model: {args.model}\n"
        "  - _self_\n"
    )
    write_config(CONFIGS / "task" / f"{task_name}.yaml", wrapper, args.force)
    log(f"task wrapper (written): configs/task/{task_name}.yaml")
    return task_name


def _task_config_import(args: argparse.Namespace) -> str:
    value = args.task_file or args.task
    candidate = Path(value).expanduser()
    if candidate.exists():
        name, target = _copy_config(candidate.resolve(), "task", args.force)
    else:
        name = value[:-5] if value.endswith(".yaml") else value
        target = CONFIGS / "task" / f"{name}.yaml"
        if not target.exists():
            die(f"找不到 task 配置: {value}（既不是文件，也不在 configs/task/ 下）")

    text = target.read_text(encoding="utf-8")
    if _flavor(text) != "task":
        die(f"{target} 不是合法的 task 配置（需要 `# @package _global_` 与 defaults:）")

    data_name = _task_data_override(text)
    if not data_name:
        die(f"{target} 的 defaults 中缺少 `override /data: <name>`")
    if not (CONFIGS / "data" / f"{data_name}.yaml").exists():
        die(f"{target} 引用的 data 配置不存在: configs/data/{data_name}.yaml")
    model_name = _task_model_override(text)
    if not (CONFIGS / "model" / f"{model_name}.yaml").exists():
        die(f"{target} 引用的 model 配置不存在: configs/model/{model_name}.yaml")
    return name


