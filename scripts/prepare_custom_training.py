def log(message: str) -> None:
    """Diagnostics go to stderr so `--print-name` produces clean stdout."""
    print(message, file=sys.stderr)


def die(message: str, code: int = 1) -> NoReturn:
    log(f"error: {message}")
    raise SystemExit(code)


def _read_json(path: Path) -> dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        die(f"文件不存在: {path}")
    except json.JSONDecodeError as exc:
        die(f"无法解析 JSON {path}: {exc}")
    raise AssertionError("unreachable")


def _sanitize(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return (slug or "custom")[:64]


def _short_hash(items: Iterable[str]) -> str:
    joined = "\n".join(items)
    return hashlib.sha1(joined.encode("utf-8")).hexdigest()[:6]


def _yaml_str(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def _dataset_yaml_path(path: Path) -> str:
    """Prefer repo-relative paths so configs stay portable inside the repo."""
    try:
        rel = path.resolve().relative_to(REPO_ROOT)
        return "./" + rel.as_posix()
    except ValueError:
        return str(path.resolve())


def _resolve_path(value: str) -> Path:
    """Config paths are interpreted relative to the repo root (launcher cwd)."""
    path = Path(str(value)).expanduser()
    if not path.is_absolute():
        path = REPO_ROOT / path
    return path


def _int_list(values: Sequence[int]) -> str:
    return "[" + ", ".join(str(int(v)) for v in values) + "]"


def _bool_list(values: Sequence[bool]) -> str:
    return "[" + ", ".join("true" if v else "false" for v in values) + "]"


