"""Generate FastWAM data/task configs from LeRobot metadata and verify training prerequisites.

Typical use (via scripts/train_custom.sh):

    python scripts/prepare_custom_training.py generate \
        --dataset ./data/my_dataset_v30 --name mybot --print-name

The generated files are `configs/data/autogen_<slug>.yaml` and
`configs/task/autogen_<slug>.yaml`. Both carry an AUTOGENERATED header; files
without that header are never overwritten unless `--force` is given.

Only the standard library is used for probing/generation, so this script works
before `pip install -e .`. The `verify`/`override-form` subcommands compose the
Hydra config and therefore require fastwam to be installed.
"""

