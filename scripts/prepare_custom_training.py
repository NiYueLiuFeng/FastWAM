def _header(datasets: Sequence[Path]) -> str:
    listed = ", ".join(str(ds.resolve()) for ds in datasets)
    first = str(datasets[0].resolve())
    return (
        f"# {AUTOGEN_MARKER}\n"
        f"# datasets: {listed}\n"
        f"# regenerate: bash scripts/train_custom.sh --dataset {first} --force\n"
    )


def _render_transforms(resize: tuple[int, int], indent: str) -> list[str]:
    return [
        f"{indent}- _target_: {TO_TENSOR_TARGET}",
        f"{indent}- _target_: {RESIZE_TARGET}",
        f"{indent}  size: {_int_list(resize)}",
    ]


def _default_lerobot_key(name: str, key: str) -> str:
    """The column the reader derives when shape_meta has no explicit lerobot_key."""
    if name == "action":
        return f"action.{key}" if key != "default" else "action"
    return f"observation.state.{key}" if key != "default" else "observation.state"


def _render_data_node(plan: Plan, node: str, is_val: bool) -> list[str]:
    policy = plan.policy
    resize = policy.resize
    lines = [f"{node}:"]
    lines.append(f"  _target_: {plan.reader}")
    lines.append("  dataset_dirs:")
    for dataset in plan.datasets:
        lines.append(f"    - {_yaml_str(_dataset_yaml_path(dataset))}")
    lines.append("  shape_meta:")
    lines.append("    images:")
    for key, raw_shape in plan.cameras:
        lines.append(f"      - key: {key}")
        lines.append(f"        raw_shape: {_int_list(raw_shape)}")
        lines.append(f"        shape: {_int_list((3, resize[0], resize[1]))}")
    for name, specs in (("action", plan.action), ("state", plan.state)):
        lines.append(f"    {name}:")
        for spec in specs:
            lines.append(f"      - key: {spec.key}")
            lines.append(f"        raw_shape: {spec.dim}")
            lines.append(f"        shape: {spec.dim}")
            # Only written when the dataset uses a non-standard column name,
            # keeping configs for standard LeRobot datasets unchanged.
            if spec.lerobot_key != _default_lerobot_key(name, spec.key):
                lines.append(f"        lerobot_key: {spec.lerobot_key}")
    lines.extend([
        f"  num_frames: {policy.num_frames}",
        f"  global_sample_stride: {policy.global_sample_stride}",
        f"  action_video_freq_ratio: {policy.action_video_freq_ratio}",
        f"  video_size: {_int_list(plan.video_size)}",
        "  camera_key: null",
        f"  val_set_proportion: {policy.val_proportion}",
        f"  is_training_set: {'false' if is_val else 'true'}",
    ])
    if not is_val:
        # Explicit null keeps `data.train.pretrained_norm_stats=...` overridable
        # without Hydra's `+` prefix. Val nodes must omit it: the runtime feeds
        # them the stats produced by the training node.
        lines.append("  pretrained_norm_stats: null")
    lines.extend([
        "  skip_padding_as_possible: false",
        f"  concat_multi_camera: {('null' if plan.concat is None else chr(34) + plan.concat + chr(34))}",
        "  processor:",
        f"    _target_: {PROCESSOR_TARGET}",
        "    shape_meta: ${data.train.shape_meta}",
        "    num_obs_steps: ${data.train.num_frames}",
        f"    num_output_cameras: {len(plan.cameras)}",
        f"    action_output_dim: {sum(spec.dim for spec in plan.action)}",
        f"    proprio_output_dim: {sum(spec.dim for spec in plan.state)}",
        "    delta_action_dim_mask:",
    ])
    offset = 0
    for spec in plan.action:
        mask = plan.delta_masks[offset:offset + spec.dim]
        offset += spec.dim
        lines.append(f"      {spec.key}: {_bool_list(mask)}")
    lines.extend([
        "    action_state_transforms: null",
        "    use_stepwise_action_norm: false",
        f"    norm_default_mode: {_yaml_str(policy.norm_mode)}",
        "    norm_exception_mode: null",
        "    action_state_merger:",
        f"      _target_: {MERGER_TARGET}",
        "    train_transforms:",
        *_render_transforms(resize, "      "),
        "    val_transforms:",
        *_render_transforms(resize, "      "),
        f"  text_embedding_cache_dir: {_yaml_str(str(policy.cache_dir))}",
        f"  use_text_embed_cache: {'true' if policy.use_text_cache else 'false'}",
        f"  context_len: {policy.context_len}",
    ])
    if plan.video_backend:
        lines.append(f"  video_backend: {plan.video_backend}")
    return lines


def render_data_yaml(plan: Plan) -> str:
    lines = [_header(plan.datasets).rstrip("\n")]
    lines.extend(_render_data_node(plan, "train", is_val=False))
    if plan.policy.val_proportion > 0:
        lines.extend(_render_data_node(plan, "val", is_val=True))
    return "\n".join(lines) + "\n"


def render_task_yaml(task_name: str, model: str, policy: Policy, datasets: Sequence[Path]) -> str:
    max_steps = "null" if policy.max_steps is None else str(policy.max_steps)
    return (
        "# @package _global_\n"
        + _header(datasets)
        + "defaults:\n"
        + f"  - override /data: {task_name}\n"
        + f"  - override /model: {model}\n"
        + "  - _self_\n"
        + "\n"
        + f"batch_size: {policy.batch_size}\n"
        + f"num_workers: {policy.num_workers}\n"
        + 'lr_scheduler_type: "cosine"\n'
        + f"learning_rate: {policy.learning_rate}\n"
        + f"num_epochs: {policy.num_epochs}\n"
        + f"max_steps: {max_steps}\n"
        + "log_every: 10\n"
        + f"save_every: {policy.save_every}\n"
        + f"keep_last_n: {policy.keep_last_n}\n"
        + "eval_every: 50\n"
        + f"gradient_accumulation_steps: {policy.gradient_accumulation_steps}\n"
        + "weight_decay: 1.0e-2\n"
        + "resume: null\n"
    )


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.replace(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass
        raise


def _header_datasets(content: str) -> list[str]:
    for line in content.splitlines():
        if line.startswith("# datasets:"):
            return [item.strip() for item in line[len("# datasets:"):].split(",") if item.strip()]
    return []


def write_config(path: Path, content: str, force: bool) -> str:
    """Write an autogenerated config; protect hand-written files."""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing.strip() == content.strip():
            return "unchanged"
        if AUTOGEN_MARKER not in existing and not force:
            die(
                f"Refusing to overwrite hand-written config {path}.\n"
                "       Re-run with --force or choose a different --name."
            )
    _atomic_write(path, content)
    return "written"


