def cmd_generate(args: argparse.Namespace) -> int:
    dataset_paths = [Path(item).expanduser().resolve() for item in args.dataset]
    missing = [str(path) for path in dataset_paths if not path.is_dir()]
    if missing:
        die(f"数据集目录不存在: {missing}")

    policy = build_policy(args)
    probes = [
        probe_dataset(path, policy.action_feature, policy.state_feature)
        for path in dataset_paths
    ]
    plan = merge_probes(probes, policy)

    base_name = policy.name
    if base_name is None:
        base_name = dataset_paths[0].name
        if len(dataset_paths) > 1:
            base_name = f"{base_name}_and_{len(dataset_paths) - 1}"
    base_slug = f"autogen_{_sanitize(base_name)}"

    dataset_ids = [str(path) for path in dataset_paths]
    slug = base_slug
    data_path = CONFIGS / "data" / f"{slug}.yaml"
    if data_path.exists():
        existing_datasets = _header_datasets(data_path.read_text(encoding="utf-8"))
        if existing_datasets and existing_datasets != dataset_ids:
            slug = f"{base_slug}_{_short_hash(dataset_ids)}"

    data_path = CONFIGS / "data" / f"{slug}.yaml"
    task_path = CONFIGS / "task" / f"{slug}.yaml"

    data_status = write_config(data_path, render_data_yaml(plan), args.force)
    task_status = write_config(
        task_path,
        render_task_yaml(slug, policy.model, policy, dataset_paths),
        args.force,
    )

    log(
        f"data config ({data_status}): {data_path.relative_to(REPO_ROOT)}\n"
        f"task config ({task_status}): {task_path.relative_to(REPO_ROOT)}"
    )
    log(
        f"cameras={[key for key, _ in plan.cameras]} "
        f"action_dim={sum(spec.dim for spec in plan.action)} "
        f"state_dim={sum(spec.dim for spec in plan.state)} "
        f"video_size={list(plan.video_size)} concat={plan.concat}"
    )

    if args.print_name:
        print(slug)
    else:
        print(data_path.relative_to(REPO_ROOT))
        print(task_path.relative_to(REPO_ROOT))
    return 0


