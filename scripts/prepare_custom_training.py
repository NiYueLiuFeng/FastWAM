def _iter_dataset_nodes(node: Any, path: str = "data"):
    from omegaconf import DictConfig, ListConfig

    if isinstance(node, DictConfig):
        if "dataset_dirs" in node and node.get("dataset_dirs") is not None:
            yield path, node
        for key, value in node.items():
            yield from _iter_dataset_nodes(value, f"{path}.{key}")
    elif isinstance(node, ListConfig):
        for index, value in enumerate(node):
            yield from _iter_dataset_nodes(value, f"{path}[{index}]")


def _last_dim(shape: Any) -> int:
    if isinstance(shape, int):
        return shape
    if isinstance(shape, (list, tuple)):
        return int(shape[-1])
    try:
        return int(shape)
    except (TypeError, ValueError):
        die(f"无法解析维度: {shape!r}")
    raise AssertionError("unreachable")


def _as_int_pair(value: Any) -> tuple[int, int] | None:
    if value is None:
        return None
    values = [int(v) for v in value]
    if len(values) != 2:
        return None
    return values[0], values[1]


def _resize_size(transforms: Any) -> tuple[int, int] | None:
    if transforms is None:
        return None
    for transform in transforms:
        target = str(transform.get("_target_", ""))
        if target.endswith("Resize"):
            size = transform.get("size")
            pair = _as_int_pair(size)
            if pair is not None:
                return pair
    return None


def check_config_semantics(cfg: Any) -> list[str]:
    errors: list[str] = []
    context_lens: dict[int, str] = {}

    for node_path, node in _iter_dataset_nodes(cfg.data):
        prefix = node_path

        num_frames = int(node.get("num_frames", 0) or 0)
        ratio = int(node.get("action_video_freq_ratio", 1) or 1)
        if num_frames < 2:
            errors.append(f"{prefix}: num_frames 必须 >= 2（当前 {num_frames}）")
        elif (num_frames - 1) % ratio != 0:
            errors.append(
                f"{prefix}: (num_frames-1)={num_frames - 1} 不能被 action_video_freq_ratio={ratio} 整除"
            )
        else:
            video_frames = (num_frames - 1) // ratio
            if video_frames % 4 != 0:
                errors.append(f"{prefix}: 视频帧数 {video_frames} 必须是 4 的倍数")

        video_size = _as_int_pair(node.get("video_size"))
        if video_size is None:
            errors.append(f"{prefix}: 缺少或无法解析 video_size")
        else:
            height, width = video_size
            if height <= 0 or width <= 0 or height % 16 or width % 16:
                errors.append(f"{prefix}: video_size={video_size} 的 H/W 必须是 16 的正整数倍")

        shape_meta = node.get("shape_meta")
        processor = node.get("processor")
        if shape_meta is None:
            errors.append(f"{prefix}: 缺少 shape_meta")
            continue
        if processor is None:
            errors.append(f"{prefix}: 缺少 processor")
            continue

        images = shape_meta.get("images") or []
        actions = shape_meta.get("action") or []
        states = shape_meta.get("state") or []

        num_cameras = processor.get("num_output_cameras")
        if num_cameras is not None and int(num_cameras) != len(images):
            errors.append(
                f"{prefix}: processor.num_output_cameras={int(num_cameras)} "
                f"与 shape_meta.images 数量 {len(images)} 不一致"
            )

        resize = _resize_size(processor.get("train_transforms"))
        if resize is not None:
            for image in images:
                image_shape = image.get("shape")
                if image_shape is None:
                    continue
                pair = _as_int_pair(list(image_shape)[-2:])
                if pair is not None and pair != resize:
                    errors.append(
                        f"{prefix}: 相机 {image.get('key')!r} 的 shape={list(image_shape)[-2:]} "
                        f"与 Resize.size={list(resize)} 不一致"
                    )

        action_dim = sum(_last_dim(item.get("shape", 0)) for item in actions)
        state_dim = sum(_last_dim(item.get("shape", 0)) for item in states)
        declared_action = processor.get("action_output_dim")
        declared_state = processor.get("proprio_output_dim")
        if declared_action is not None and int(declared_action) != action_dim:
            errors.append(
                f"{prefix}: processor.action_output_dim={int(declared_action)} "
                f"与 shape_meta.action 之和 {action_dim} 不一致"
            )
        if declared_state is not None and int(declared_state) != state_dim:
            errors.append(
                f"{prefix}: processor.proprio_output_dim={int(declared_state)} "
                f"与 shape_meta.state 之和 {state_dim} 不一致"
            )

        masks = processor.get("delta_action_dim_mask")
        if masks is not None:
            action_keys = [str(item.get("key")) for item in actions]
            if set(masks.keys()) != set(action_keys):
                errors.append(
                    f"{prefix}: delta_action_dim_mask keys {list(masks.keys())} "
                    f"与 action keys {action_keys} 不一致"
                )
            else:
                for item in actions:
                    key = str(item.get("key"))
                    dim = _last_dim(item.get("shape", 0))
                    if len(masks[key]) != dim:
                        errors.append(
                            f"{prefix}: delta_action_dim_mask[{key!r}] 长度 {len(masks[key])} "
                            f"与 action 维度 {dim} 不一致"
                        )

        context_len = node.get("context_len")
        if context_len is not None:
            context_lens.setdefault(int(context_len), node_path)

    if len(context_lens) > 1:
        detail = ", ".join(f"{value} ({path})" for value, path in sorted(context_lens.items()))
        errors.append(f"data 节点间的 context_len 不一致: {detail}")

    return errors


def _model_id_to_enc_id(model_id: str) -> str:
    base = str(model_id).split("/")[-1]
    enc_id = re.sub(r"[^a-z0-9]+", "", base.lower())
    return enc_id or "textenc"


def _default_prompt() -> str:
    try:
        from fastwam.datasets.lerobot.robot_video_dataset import DEFAULT_PROMPT
    except Exception as exc:  # pragma: no cover - environment issue
        die(f"无法导入 fastwam.datasets: {exc}。请先执行 pip install -e .")
    return DEFAULT_PROMPT


def check_backbone(cfg: Any, task: str, random_init: bool) -> list[str]:
    if random_init:
        return []
    model = cfg.get("model")
    if model is None:
        return ["缺少 model 配置"]
    if bool(model.get("skip_dit_load_from_pretrain", False)):
        return []
    raw_path = model.get("action_dit_pretrained_path")
    if not raw_path:
        return []

    backbone = Path(str(raw_path)).expanduser()
    if not backbone.is_absolute():
        backbone = REPO_ROOT / backbone
    if backbone.exists():
        return []

    model_name = _task_model_override((CONFIGS / "task" / f"{task}.yaml").read_text(encoding="utf-8"))
    return [
        f"缺少 ActionDiT backbone: {backbone}",
        "  请先运行：",
        "    python scripts/preprocess_action_dit_backbone.py \\",
        f"      --model-config configs/model/{model_name}.yaml \\",
        f"      --output {backbone} \\",
        "      --device cuda --dtype bfloat16",
        "  或在启动时加 --random-backbone-init（不推荐，会随机初始化动作专家）。",
    ]


def check_text_cache(cfg: Any, online_text_encode: bool, gpus: int, task: str) -> list[str]:
    if online_text_encode:
        return []

    enc_id = _model_id_to_enc_id(str(cfg.model.get("model_id", DEFAULT_MODEL_ID)))
    prompt_template = _default_prompt()
    missing: list[str] = []
    problems: list[str] = []
    saw_dataset = False

    for node_path, node in _iter_dataset_nodes(cfg.data):
        if not bool(node.get("use_text_embed_cache", True)):
            continue
        saw_dataset = True
        cache_dir = node.get("text_embedding_cache_dir")
        if not cache_dir:
            problems.append(f"{node_path}: 开启了文本缓存但缺少 text_embedding_cache_dir")
            continue
        cache_path = _resolve_path(str(cache_dir))
        context_len = int(node.get("context_len", DEFAULT_CONTEXT_LEN))

        for dataset in node.dataset_dirs:
            dataset_path = _resolve_path(str(dataset))
            if not dataset_path.exists():
                problems.append(f"{node_path}: 数据集目录不存在: {dataset_path}")
                continue
            try:
                tasks = read_task_texts(dataset_path)
            except SystemExit:
                raise
            except Exception as exc:
                problems.append(f"{node_path}: 无法读取任务文本 ({dataset_path}): {exc}")
                continue
            if not tasks:
                problems.append(f"{node_path}: {dataset_path} 的任务文本为空")
                continue
            for task_text in tasks:
                prompt = prompt_template.format(task=task_text)
                digest = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
                expected = cache_path / f"{digest}.t5_len{context_len}.{enc_id}.pt"
                if not expected.exists():
                    missing.append(str(expected))

    if not saw_dataset:
        return []

    if problems:
        return problems

    if missing:
        unique_missing = sorted(set(missing))
        lines = [f"文本嵌入缓存不完整：缺少 {len(unique_missing)} 个文件（示例 {unique_missing[0]}）",
                 "  请先运行：",
                 f"    python scripts/precompute_text_embeds.py task={task}",
                 f"    torchrun --standalone --nproc_per_node={gpus} scripts/precompute_text_embeds.py task={task}",
                 "  或免缓存在线编码：",
                 "    bash scripts/train_custom.sh --task "
                 f"{task} --online-text-encode"]
        return lines
    return []


def _print_problems(title: str, lines: Sequence[str]) -> None:
    log(f"error: {title}")
    for line in lines:
        log(f"  {line}" if not line.startswith("  ") else line)


def cmd_verify(args: argparse.Namespace) -> int:
    cfg = compose_config(args.task, args.override or [])

    errors = check_config_semantics(cfg)
    if errors:
        _print_problems("配置校验失败：", errors)
        return 1

    if args.skip_prereq_check:
        log("prerequisite check skipped (--skip-prereq-check)")
        return 0

    prereq: list[str] = []
    prereq.extend(check_backbone(cfg, args.task, args.random_backbone_init))
    if prereq:
        _print_problems("训练前置条件缺失：", prereq)
        return 2

    cache_problems = check_text_cache(cfg, args.online_text_encode, args.gpus, args.task)
    if cache_problems:
        _print_problems("训练前置条件缺失：", cache_problems)
        return 2

    log("config + prerequisites OK")
    return 0


